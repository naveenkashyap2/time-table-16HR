import { memo } from 'react';
import { Quote as QuoteIcon, RefreshCw, WifiOff, Sparkles } from 'lucide-react';
import Button from '../common/Button.jsx';
import { useQuote } from '../../hooks/useQuote.js';

/** Daily Gemini quote with shimmer loading + local fallback (§10.2.2). */
function QuoteCard() {
  const { quote, loading, refresh, fetchesLeft, enabled } = useQuote();

  if (!enabled) return null;

  return (
    <section className="quote-card" aria-label="Daily motivation">
      <span aria-hidden="true" style={{ opacity: 0.9, flex: '0 0 auto' }}>
        <QuoteIcon size={26} />
      </span>

      <div className="grow" style={{ minWidth: 0 }}>
        {loading ? (
          <div aria-busy="true" aria-live="polite">
            <span className="sr-only">Loading today&rsquo;s quote…</span>
            <div className="quote-skel" style={{ width: '92%', marginBottom: 10 }} />
            <div className="quote-skel" style={{ width: '64%' }} />
          </div>
        ) : (
          <>
            <p className="quote-text">{quote?.text}</p>
            <p className="quote-meta row" style={{ gap: 6 }}>
              {quote?.source === 'gemini' ? (
                <>
                  <Sparkles size={13} aria-hidden="true" /> Generated by Gemini
                </>
              ) : (
                <>
                  <WifiOff size={13} aria-hidden="true" /> Offline quote
                </>
              )}
              <span aria-hidden="true">·</span>
              <span>{fetchesLeft} refresh{fetchesLeft === 1 ? '' : 'es'} left today</span>
            </p>
          </>
        )}
      </div>

      <Button
        size="sm"
        icon={RefreshCw}
        onClick={refresh}
        disabled={loading || fetchesLeft <= 0}
        aria-label="Generate a new quote"
        style={{ flex: '0 0 auto' }}
      >
        New Quote
      </Button>
    </section>
  );
}

export default memo(QuoteCard);
